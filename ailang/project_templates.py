def create_project(
    name: str,
    template: str = "app",
    dest: Optional[str] = None,
) -> Path:
    """Crea un proyecto desde un template.

    Args:
        name: nombre del proyecto
        template: tipo de template ("app", "lib", "web", "script")
        dest: directorio destino (default: ./name)

    Returns:
        Path al directorio del proyecto creado
    """
    if template not in _TEMPLATES:
        raise ValueError(
            f"template desconocido: {template}. "
            f"Disponibles: {', '.join(_TEMPLATES.keys())}"
        )

    root = Path(dest or name)
    root.mkdir(parents=True, exist_ok=True)

    name_camel = name.replace("-", "_").replace(" ", "_").title().replace("_", "")

    template_files = _TEMPLATES[template]
    for filename, content in template_files.items():
        filepath = root / filename
        filepath.parent.mkdir(parents=True, exist_ok=True)
        # Template variables — use string replace instead of format to avoid { } conflicts
        filled = content
        filled = filled.replace("{name}", name)
        filled = filled.replace("{name_camel}", name_camel)
        filled = filled.replace("{version}", __version__)
        filepath.write_text(filled, encoding="utf-8")

    return root


def list_templates() -> Dict[str, str]:
    """Retorna los templates disponibles con su descripción."""
    return {
        "app": "Application with main(), tests, CI",
        "lib": "Reusable library with public API",
        "web": "Web server with HTTP handler",
        "script": "Simple script (single file)",
    }
